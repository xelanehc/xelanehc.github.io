type OgImage = { url: string; width: number; height: number; alt: string };

/** Generated by src/app/og/[image]/route.tsx. */
export function ogImage(name: string, alt: string): OgImage {
  return { url: `/og/${name}.png`, width: 1200, height: 630, alt };
}

export const defaultOgImage = ogImage("home", "Alex Chen, software engineer");

/**
 * Per-page metadata with matching Open Graph fields and a canonical URL.
 * `path` is the route without a trailing slash ("/projects"); the exported
 * URL gets one (trailingSlash: true).
 */
export function pageMetadata({
  title,
  description,
  path,
  image = defaultOgImage,
}: {
  title: string;
  description: string;
  path: string;
  image?: OgImage;
}): Metadata {
  const canonical = path === "/" ? "/" : `${path}/`;
  return {
    title,
    description,
    alternates: { canonical },
    openGraph: { title, description, url: canonical, images: [image] },
    twitter: { title, description, images: [image] },
  };
}
